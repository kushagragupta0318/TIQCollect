"""Generate the event-sourced synthetic book and its Phase 1 realism report.

    python -m scripts.build_ledger_dataset --tier dev
    python -m scripts.build_ledger_dataset --tier full
    python -m scripts.build_ledger_dataset --tier full --no-calibrate

WHY THIS IS NOT scripts/build_modelling_dataset.py. That one drives
`book_simulator`, which emits aggregated features directly and remains the
BASELINE — `recovery_risk` 1.1.0 (OOT Gini 0.5136) was trained on it and nothing
here replaces it. This one drives the event-sourced simulator: it writes an
append-only ledger and DERIVES the panel from it, so the same frame can later be
checked against the production adapter.

PHASE 1 ONLY. This builds the ledger, derives the panel, and runs the realism
checks. It does NOT train anything. Model-facing checks — the Gini band, the
DPD-alone ratio, the IV ceiling, the oracle gap — belong to Phase 2 and are
deliberately not reachable from here, so the generator cannot be tuned against a
model result.

Output goes to backend/data/ledger/<tier>/, which .gitignore already covers via
the backend/data block. The dataset is regenerable from the seed in its own
metadata; a parquet of synthetic borrowers does not belong in git.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import replace
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from app.ml.simulation.ledger import LedgerConfig, LedgerSimulator  # noqa: E402
from app.ml.simulation.ledger.panel import build_panel  # noqa: E402
from app.ml.simulation.ledger.realism import (  # noqa: E402
    format_report, realism_report,
)

DATA_ROOT = BACKEND / "data" / "ledger"

TIERS = {
    "dev": LedgerConfig(n_borrowers=1_000, months=12, seed=42),
    # 24 months so the last six can be a genuine out-of-time holdout under the
    # 0.60/0.15 chronological split ModelSpec already uses.
    "full": LedgerConfig(n_borrowers=5_000, months=24, seed=42),
    # Concept drift ON. Its purpose is to make monitor_model's retrain trigger
    # demonstrably fire; its headline metrics are NOT comparable with the
    # baseline and the metadata says so.
    "stress": LedgerConfig(n_borrowers=5_000, months=24, seed=42,
                           concept_drift=True),
}


def build(tier: str, *, calibrate: bool = True) -> dict:
    cfg = TIERS[tier]
    out = DATA_ROOT / tier
    out.mkdir(parents=True, exist_ok=True)

    intercept = -4.1562
    if calibrate:
        # PREVALENCE ONLY — the intercept shifts every borrower's hazard by the
        # same amount on the log-odds scale, so it moves the base rate without
        # touching any driver's relative weight. See LedgerSimulator.calibrate.
        probe = replace(cfg, n_borrowers=min(cfg.n_borrowers, 900), months=12)
        intercept = LedgerSimulator(probe).calibrate(
            probe_borrowers=probe.n_borrowers, probe_months=probe.months)

    sim = LedgerSimulator(cfg)
    ledger = sim.run(intercept=intercept)
    panel = build_panel(ledger, cfg)
    report = realism_report(ledger, panel, cfg)

    for name, df in ledger.tables().items():
        if len(df):
            df.to_parquet(out / f"{name}.parquet", index=False)
    panel.to_parquet(out / "panel.parquet", index=False)

    meta = {
        "tier": tier,
        "intercept": round(intercept, 5),
        "calibrated": calibrate,
        "config": ledger.config,
        "realism": report,
        "SYNTHETIC_WARNING":
            "Generated by app/ml/simulation/ledger/. These are SYNTHETIC "
            "borrowers. The realism checks say the book is internally "
            "plausible; they are NOT evidence about real borrowers, and almost "
            "every acceptance band is a PROJECT ASSUMPTION with no external "
            "source. See config.BANDS for the provenance of each.",
        "BASELINE_NOTE":
            "book_simulator.py is unchanged and remains the baseline. "
            "recovery_risk 1.1.0 was trained on it; nothing here is promoted.",
    }
    (out / "dataset_metadata.json").write_text(
        json.dumps(meta, indent=2, default=str), encoding="utf-8")
    (out / "REALISM_REPORT.txt").write_text(format_report(report), encoding="utf-8")

    print(format_report(report))
    print(f"written to {out}")
    print(f"realism: {'PASS' if report['passed'] else 'FAIL'}"
          f" ({report['n_failed']} failed)")
    return meta


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", choices=list(TIERS), default="dev")
    ap.add_argument("--no-calibrate", action="store_true")
    a = ap.parse_args()
    meta = build(a.tier, calibrate=not a.no_calibrate)
    # Non-zero exit when the book is not plausible, so a pipeline cannot
    # proceed to training on a book that failed its own acceptance checks.
    return 0 if meta["realism"]["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
