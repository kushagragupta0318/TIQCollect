// Single source of truth for the month's assigned-case count: whatever the
// leaderboard rows say. Always the full agency list, not the filtered view —
// the card is labelled "Total", so the agency dropdown must not change it.
function getTotalAssignedCases(month){

    return dashboardData[month].leaderboard.reduce(
        (total, entry) => total + entry.cases,
        0
    );

}

function updateKPIs(month){

    const data = dashboardData[month].kpis;

    // ==========================
    // Update KPI Values
    // ==========================

    document.getElementById("collectionRate").innerHTML =
        data.collection + "%";

    document.getElementById("ptpRate").innerHTML =
        data.ptp + "%";

    // "Total Assigned Cases" is derived, never hand-entered: it is the sum of
    // the Cases Assigned column in the leaderboard for the same month, so the
    // card can never disagree with the table underneath it.
    document.getElementById("casesAssigned").innerHTML =
        getTotalAssignedCases(month).toLocaleString();

    document.getElementById("agencyCount").innerHTML =
        data.agencies;

    // ==========================
    // Collection Rate Comparison
    // ==========================

    const collectionChange =
    (
        (
            data.collection -
            data.previousCollection
        )
        /
        data.previousCollection
        * 100
    ).toFixed(1);

    const changeElement =
    document.getElementById("collectionChange");

    if(collectionChange >= 0){

        changeElement.innerHTML =
        `▲ ${collectionChange}%`;

        changeElement.className =
        "change-value change-up";

    }
    else{

        changeElement.innerHTML =
        `▼ ${Math.abs(collectionChange)}%`;

        changeElement.className =
        "change-value change-down";

    }

    // ==========================
    // PTP Comparison
    // ==========================

    const ptpChange =
    (
        (
            data.ptp -
            data.previousPTP
        )
        /
        data.previousPTP
        * 100
    ).toFixed(1);

    const ptpElement =
    document.getElementById("ptpChange");
    const trendElement =
    document.getElementById("ptpTrend");
    if(ptpChange >= 0){

    ptpElement.innerHTML =
    `▲ ${ptpChange}%`;

    ptpElement.className =
    "change-value change-up";

    trendElement.innerHTML = "↗";

    trendElement.className =
    "trend-indicator trend-up";

}
else{

    ptpElement.innerHTML =
    `▼ ${Math.abs(ptpChange)}%`;

    ptpElement.className =
    "change-value change-down";

    trendElement.innerHTML = "↘";

    trendElement.className =
    "trend-indicator trend-down";

}
}

