function getLastSixMonths(selectedMonth){

    const months = [
        "Jan","Feb","Mar","Apr","May","Jun",
        "Jul","Aug","Sep","Oct","Nov","Dec"
    ];

    const labels = [];

    const currentIndex = months.indexOf(selectedMonth);

    for(let i = 5; i >= 0; i--){

        let index = currentIndex - i;

        let year = 2026;

        if(index < 0){

            index += 12;

            year = 2025;

        }

        labels.push(months[index] + " " + year);

    }

    return labels;

}

