// =========================================================
// Trend chart "draw-in" reveal
// -----------------------------------------------------------
// Rather than animating each point in on its own staggered
// delay (which reads as a jerky, step-by-step reveal), this
// clips the ENTIRE chart (lines + points together) to a
// rectangle that grows smoothly from the left edge of the
// chart area to the right, once, over a fixed duration. That
// gives one continuous left-to-right "pen trace" sweep, with
// each point simply appearing the instant the sweep passes
// its x position - matching a single, fluid draw-in instead
// of a segmented one.
// =========================================================
if (typeof Chart !== "undefined") {
    Chart.register({
        id: "lineRevealClip",
        beforeDatasetsDraw(chart) {
            const progress = chart.$reveal;
            if (progress === undefined || progress >= 1) return;
            const { ctx, chartArea } = chart;
            const revealRight = chartArea.left + chartArea.width * progress;
            ctx.save();
            ctx.beginPath();
            ctx.rect(
                chartArea.left - 20,
                chartArea.top - 20,
                (revealRight - chartArea.left) + 20,
                chartArea.height + 40
            );
            ctx.clip();
        },
        afterDatasetsDraw(chart) {
            const progress = chart.$reveal;
            if (progress === undefined || progress >= 1) return;
            chart.ctx.restore();
        }
    });
}

// Kicks off the left-to-right reveal sweep on a freshly built chart.
// Call this once, right after `new Chart(...)`, each time the trend
// chart is (re)built so the sweep replays on every rebuild.
function playTrendReveal(chart, duration = 1200) {
    chart.$reveal = 0;
    const start = performance.now();

    function step(now) {
        const t = Math.min((now - start) / duration, 1);
        chart.$reveal = t;
        chart.draw();
        if (t < 1) {
            requestAnimationFrame(step);
        } else {
            chart.$reveal = 1;
        }
    }

    requestAnimationFrame(step);
}

