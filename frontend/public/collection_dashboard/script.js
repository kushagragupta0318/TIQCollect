const managerLinks = {};

// Months in chronological order as they exist in dashboardData.
// Feb has no earlier month in the dataset, so it won't show a trend badge.
const leaderboardMonthOrder = ["Feb","Mar","Apr","May","Jun","Jul"];

function getPreviousMonthKey(month){
    const idx = leaderboardMonthOrder.indexOf(month);
    return idx > 0 ? leaderboardMonthOrder[idx - 1] : null;
}

function getPreviousAgencyEntry(month, agencyName){
    const prevMonth = getPreviousMonthKey(month);
    if(!prevMonth || !dashboardData[prevMonth]) return null;
    return dashboardData[prevMonth].leaderboard.find(
        a => a.agency === agencyName
    ) || null;
}

// "₹12.80 Cr" -> 12.80
function parseAmount(amountStr){
    return parseFloat(
        amountStr.replace("₹","").replace("Cr","").replace(",","").trim()
    );
}

// Builds the small "▲ 2.3%" / "▼ 1.1%" badge shown next to a value.
// Returns "" when there's no previous month to compare against.
function trendBadge(current, previous){
    if(previous === null || previous === undefined || previous === 0){
        return "";
    }

    const change = (((current - previous) / previous) * 100).toFixed(1);

    if(change >= 0){
        return `<span class="mini-trend mini-up">▲ ${change}%</span>`;
    }
    else{
        return `<span class="mini-trend mini-down">▼ ${Math.abs(change)}%</span>`;
    }
}

function getColor(value){

    if(value >= 90) return "green";

    if(value >= 75) return "orange";

    return "red";

}

function renderTable(data, month){

    tbody.innerHTML = "";

    data.forEach(item=>{

        const prevEntry = getPreviousAgencyEntry(month, item.agency);

        const collectionBadge = trendBadge(
            item.collection,
            prevEntry ? prevEntry.collection : null
        );

        const ptpBadge = trendBadge(
            item.ptp,
            prevEntry ? prevEntry.ptp : null
        );

        const amountBadge = trendBadge(
            parseAmount(item.amount),
            prevEntry ? parseAmount(prevEntry.amount) : null
        );

        // collection_dashboard: clickable agency name deep-links into that manager's analytics view
        const agencyLink = managerLinks[item.agency];
        // const agencyCell = agencyLink
        //     ? `<a href="${agencyLink}" class="agency-link">${item.agency}</a>`
        //     : item.agency;

        const agencyCell = `
        <a href="#"
            class="agency-link"
            onclick="openManagerDashboard('${item.agency}'); return false;">
            ${item.agency}
        </a>
        `;

        tbody.innerHTML += `

        <tr>

            <td class="rank">${item.rank}</td>

            <td>${agencyCell}</td>

            <td class="${getColor(item.collection)}"><div class="cell-inline"><span class="cell-value">${item.collection}%</span>${collectionBadge}</div></td>

            <td><div class="cell-inline"><span class="cell-value">${item.ptp}%</span>${ptpBadge}</div></td>

            <td>${item.cases.toLocaleString()}</td>

            <td class="amount"><div class="cell-inline"><span class="cell-value">${item.amount}</span>${amountBadge}</div></td>

            <td>${item.agents}</td>

        </tr>

        `;

    });

}

